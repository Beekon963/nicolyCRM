-- =============================================================================
-- Phase 9: NICOLY フォーマット（2026-10-12 にいただいた形）
--
-- 最初に入れておいた仮の「NICOLY用」の書式を、いただいた形に置きかえる（オーナーが直していないときだけ）。
--   【NICOLY フォーマット】
--   {日付} {会場}
--   {稼働者}
--   【実績】
--   {当日・後日の実績}   … 「当日」「後日」に分けて「新規1(山田)」の形で1人ずつ（後日は「〇〇（後日）」の項目）
--   {所感}               … コメント（なければ出ない）
-- 現場ごとに1通で、2人以上の現場は全員分をまとめる（マイページでは代表の1人が送る）
-- =============================================================================

update public.report_formats
   set header = '',
       event_block = E'【NICOLY フォーマット】\n\n{日付} {会場}\n{稼働者}\n\n【実績】\n{当日・後日の実績}\n\n{所感}\n',
       person_block = '',
       footer = ''
 where name = 'NICOLY用'
   and company_id is null
   and header = E'【日報】{日付}（{曜日}）{取引先}'
   and event_block = E'■{会場}'
   and person_block = E'{名前}（{役割}）\n{件数一覧}\n{コメント}'
   and footer = '';
