-- =============================================================================
-- Phase 11: LINE のトーク履歴から取り込んだ、件数の記録だけの現場
--
-- 過去の件数の報告を取り込むとき、CRM にその日の現場がなければ「記録のみ」の現場を作る。
-- この現場はスタッフの平均獲得件数・実績の分析のためだけのもので、お金の計算（請求・報酬）には入れない
-- （単価が決まっていない過去の現場を、取引先の標準単価で請求・支払いに足してしまわないように）。
-- =============================================================================

alter table public.events add column counts_only boolean not null default false;

comment on column public.events.counts_only is '件数の記録だけの現場（LINE のトーク履歴から取り込み）。お金の計算には入れない';
